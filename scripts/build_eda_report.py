Y24, Y25 = DATA


def n(value):
    return f'{value:,}' if isinstance(value, int) else f'{value:,.2f}'


def wan(value):
    return f'{value / 10000:,.1f}'


def pct(value):
    return f'{value:.2f}%' if value is not None else '—'


def table(headers, rows):
    out = ['| ' + ' | '.join(headers) + ' |', '| ' + ' | '.join(['---'] * len(headers)) + ' |']
    for row in rows:
        out.append('| ' + ' | '.join(str(c) for c in row) + ' |')
    return '\n'.join(out)


def growth(new, old):
    return (new - old) / old * 100 if old else None


def route_map(year):
    return {r['route']: r for r in year['route_table']}


def category_map(year):
    return {r['category']: r for r in year['category_table_enriched']}


r24, r25 = route_map(Y24), route_map(Y25)
c24, c25 = category_map(Y24), category_map(Y25)

